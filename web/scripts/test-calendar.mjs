import assert from 'node:assert/strict';
import {calendarState, calendarSummary} from '../shared/calendar.js';
const asOf='2026-10-27';
const plan={kind:'habit',start:'2026-10-01',end:'2026-10-31',weekdays:[1,3,5],tasks:[],items:[],unit:'',notes:''};
const habit={id:'habit',title:'Meu SONHO',target:12,color:'sage',plan,days:['2026-10-26'],entries:[],failures:['2026-10-23'],created_at:'2026-10-10T12:00:00Z'};
const before=JSON.stringify(habit);
assert.equal(calendarState(habit,'2026-10-28',asOf).status,'planejado');
assert.equal(calendarState(habit,'2026-10-27',asOf).visible,false);
assert.equal(calendarState(habit,'2026-11-02',asOf).visible,false);
assert.equal(calendarState(habit,'2026-10-02',asOf).planned,true,'Explicit past start survives later creation');
assert.equal(calendarState(habit,'2026-10-26',asOf).status,'feito');
assert.equal(calendarState(habit,'2026-10-23',asOf).status,'não cumprido');
assert.equal(calendarState({...habit,entries:[{key:'task',day:'2026-10-21',value:1}]},'2026-10-21',asOf).status,'em andamento');
assert.equal(calendarState({...habit,plan:{...plan,start:''}},'2026-10-05',asOf).planned,false,'Never invent schedules before creation');
assert.equal(calendarState({...habit,plan:{...plan,start:''},created_at:'2026-10-10T01:00:00Z'},'2026-10-09',asOf).planned,true,'Creation date uses São Paulo');
const finished={...habit,target:1,plan:{...plan,start:'',end:''}};
assert.equal(calendarState(finished,'2026-10-28',asOf).planned,false,'Finished undated dreams do not repeat indefinitely');
const list={...habit,days:[],failures:[],plan:{...plan,kind:'list',items:[{id:'book',date:'2026-10-28'}]},entries:[{key:'book',day:'2026-10-27',value:1}]};
assert.equal(calendarState(list,'2026-10-28',asOf).status,'planejado','Keep planned date separate from actual completion');
assert.equal(calendarState(list,'2026-10-27',asOf).status,'feito');
assert.equal(calendarState(list,'2026-10-29',asOf).visible,false,'One-time lists do not recur');
const amount={...habit,target:10,days:[],failures:[],plan:{...plan,kind:'amount',end:'2026-10-31'},entries:[{key:'a',day:'2026-10-24',value:4},{key:'b',day:'2026-10-26',value:6}]};
assert.equal(calendarState(amount,'2026-10-31',asOf).status,'planejado');
assert.equal(calendarState(amount,'2026-10-24',asOf).status,'em andamento');
assert.equal(calendarState(amount,'2026-10-26',asOf).status,'feito');
assert.equal(calendarState(amount,'2026-10-28',asOf).visible,false,'Amount goals are not daily habits');
assert.equal(JSON.stringify(habit),before,'Calendar must not mutate records');
console.log('PASS: planned vs actual stickers, schedules, São Paulo creation dates, completed habits, one-time lists, quantities, failures, partial entries and immutable records.');

assert.deepEqual(calendarSummary([],asOf,asOf),{total:0,completed:0,percent:0});
const mixed=[{planned:true,done:true},{planned:true,done:false,failed:true},{planned:true,done:false,partial:true},{done:true,planned:false}];
assert.deepEqual(calendarSummary(mixed,asOf,asOf),{total:4,completed:2,percent:50});
assert.equal(calendarSummary(mixed,'2026-10-28',asOf).percent,0,'Future days stay neutral');
assert.equal(calendarSummary([{planned:true,done:true}],asOf,asOf).percent,100);
